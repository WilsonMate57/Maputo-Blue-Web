-- ─────────────────────────────────────────────────────────────────────────────
-- 009_analytics.sql — First-party visit statistics (admin → Estatísticas).
-- No cookies and no personal data: a visitor is a hash of (secret salt, day,
-- IP, browser) that changes every day; a session is a random id kept in the
-- tab's sessionStorage. Clicks keep only the position on the page and the
-- text of the button or link (never what was typed in a form).
-- ─────────────────────────────────────────────────────────────────────────────

create table analytics_pageviews (
  id            uuid primary key,                 -- generated by the browser
  session_id    text not null,
  visitor_hash  text not null,                    -- rotates daily
  at            timestamptz not null default now(),
  path          text not null,                    -- e.g. /pages/package.html?id=sunset-cruise
  locale        text,
  title         text,
  referrer_host text,                             -- null = direct / unknown
  utm_source    text,
  utm_medium    text,
  utm_campaign  text,
  device        text not null check (device in ('mobile','tablet','desktop')),
  browser       text,
  os            text,
  viewport_w    integer,
  engaged_ms    integer not null default 0,       -- time with the page visible
  scroll_pct    smallint not null default 0       -- deepest point reached
);
create index analytics_pageviews_at_idx on analytics_pageviews (at);
create index analytics_pageviews_path_idx on analytics_pageviews (path, at);
create index analytics_pageviews_session_idx on analytics_pageviews (session_id);

create table analytics_clicks (
  id           bigserial primary key,
  pageview_id  uuid not null references analytics_pageviews(id) on delete cascade,
  at           timestamptz not null default now(),
  path         text not null,
  device       text not null check (device in ('mobile','tablet','desktop')),
  x            real not null,                     -- fraction of the page width (0–1)
  y            integer not null,                  -- px from the top of the page
  label        text,                              -- text of the button / link
  tag          text,
  href         text
);
create index analytics_clicks_page_idx on analytics_clicks (path, device, at);
create index analytics_clicks_at_idx on analytics_clicks (at);
